/** 取动作的详解数据；自建动作 / 未收录动作返回 null（界面回落库里那段 tips） */
export function guideOf(exerciseId: string | null | undefined): ExerciseGuide | null {
  if (!exerciseId) return null
  return EXERCISE_GUIDES[exerciseId] ?? null
}

/**
 * 单组动作预计秒数 —— 动作倒计时的右侧刻度。
 *
 *   力量：次数 × 每次循环秒数（`repSec`）
 *   计时 / 有氧：各自的处方秒数（`targetSec`），没有就用分钟换算
 *
 * 三个输入都没有时给一个保守的 40 秒：倒计时宁可长一点也不要在动作中途就转橙。
 */
export const FALLBACK_SET_SEC = 40

export function setDurationSec(
  guide: ExerciseGuide | null,
  kind: ExerciseKind,
  reps: number | null,
  targetSec: number | null,
  durationMin: number | null,
): number {
  if (kind === 'strength' && guide && guide.repSec > 0 && reps != null && reps > 0) {
    return Math.round(reps * guide.repSec)
  }
  if (targetSec != null && targetSec > 0) return targetSec
  if (durationMin != null && durationMin > 0) return durationMin * 60
  return FALLBACK_SET_SEC
}
